"""File storage behind one small interface.

The photo code only calls put / get / delete with a key. Which place actually
keeps the bytes is decided once by STORAGE_BACKEND:

- "local": a folder inside the container (laptop development and tests)
- "oci":   OCI Object Storage, authenticated as the instance itself
           (instance principal), so no key file or password lives on the server

Keys are always generated by the server (never taken from the request).
"""

import logging
from functools import lru_cache
from pathlib import Path
from typing import Protocol

from app.config import settings

logger = logging.getLogger(__name__)


class Storage(Protocol):
    def put(self, key: str, data: bytes, content_type: str) -> None: ...

    def get(self, key: str) -> bytes | None: ...

    def delete(self, key: str) -> None: ...


class LocalStorage:
    """Stores each object as a file under root/<key>."""

    def __init__(self, root: str) -> None:
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        # Defence in depth: keys come from our own code, but never let one escape the root.
        if not path.is_relative_to(self.root):
            raise ValueError("Storage key points outside the storage root")
        return path

    def put(self, key: str, data: bytes, content_type: str) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def get(self, key: str) -> bytes | None:
        path = self._path(key)
        if not path.is_file():
            return None
        return path.read_bytes()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


class OciStorage:
    """One OCI Object Storage bucket, signed with the instance principal."""

    def __init__(self, region: str, bucket: str) -> None:
        # Imported here so laptop/tests with STORAGE_BACKEND=local never need OCI metadata access.
        import oci

        self._oci = oci
        signer = oci.auth.signers.InstancePrincipalsSecurityTokenSigner()
        self.client = oci.object_storage.ObjectStorageClient(config={"region": region}, signer=signer)
        # The namespace is looked up at start instead of being stored in .env.
        self.namespace = self.client.get_namespace().data
        self.bucket = bucket

    def put(self, key: str, data: bytes, content_type: str) -> None:
        self.client.put_object(self.namespace, self.bucket, key, data, content_type=content_type)

    def get(self, key: str) -> bytes | None:
        try:
            response = self.client.get_object(self.namespace, self.bucket, key)
        except self._oci.exceptions.ServiceError as exc:
            if exc.status == 404:
                return None
            raise
        return response.data.content

    def delete(self, key: str) -> None:
        try:
            self.client.delete_object(self.namespace, self.bucket, key)
        except self._oci.exceptions.ServiceError as exc:
            if exc.status != 404:
                raise


@lru_cache
def get_private_storage() -> Storage:
    """Storage for photos only the owner may see (profile, yarn label, finished pattern)."""
    if settings.storage_backend == "oci":
        return OciStorage(settings.oci_region, settings.oci_private_bucket)
    return LocalStorage(str(Path(settings.local_storage_dir) / settings.oci_private_bucket))
